#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const outDir = path.join(root, "dist");

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(srcPath, destPath);
    else if (entry.isFile()) fs.copyFileSync(srcPath, destPath);
  }
}

function copyFile(relativePath) {
  const src = path.join(root, relativePath);
  const dest = path.join(outDir, relativePath);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

copyFile("index.html");
copyDir(path.join(root, "css"), path.join(outDir, "css"));
copyDir(path.join(root, "js"), path.join(outDir, "js"));
copyDir(path.join(root, "assets"), path.join(outDir, "assets"));

// Only the two DERIVED, data-only map files ship - never Paradox's original
// locations.png artwork / definitions.txt / named_locations (see
// map_data/README.md and docs/ARCHITECTURE.md's "Map" section for why that
// distinction matters). Both are optional locally (see root README's "Map
// setup") - a contributor's checkout without them still builds fine, just
// without the Map tab/Home backdrop working.
const MAP_DATA_FILES = ["location_ids.png", "locations.json"];
let mapDataShipped = 0;
for (const name of MAP_DATA_FILES) {
  const src = path.join(root, "map_data", name);
  if (fs.existsSync(src)) {
    copyFile(path.join("map_data", name));
    mapDataShipped++;
  }
}
if (mapDataShipped < MAP_DATA_FILES.length) {
  console.warn(`map_data/ not fully set up locally (${mapDataShipped}/${MAP_DATA_FILES.length} files found) - Map tab/Home backdrop won't work in this build. See root README's "Map setup".`);
}

// Same treatment as map_data/ above: game_data/building-costs.json is
// DERIVED, data-only numbers (tools/build-building-costs.js's output from
// the player's own local install), never Paradox's original text files, so
// it's safe to ship even though the whole game_data/ directory is
// gitignored - see that tool's own header comment for how it's generated.
// Optional locally, same as map_data - a checkout without it still builds,
// just without the Buildings Value economic metric.
const gameDataBuildingCostsSrc = path.join(root, "game_data", "building-costs.json");
if (fs.existsSync(gameDataBuildingCostsSrc)) {
  copyFile(path.join("game_data", "building-costs.json"));
} else {
  console.warn(`game_data/building-costs.json not found - Buildings Value metric won't work in this build. Run: node tools/build-building-costs.js`);
}

// Public shared-save backend config (see config.example.js / js/share-store.js).
// Generated fresh from the Netlify build env vars - NOT copied from any local
// config.js, so a developer's local creds can never leak into a deploy. If the
// vars aren't set, ship no config.js at all and the app degrades to local-only
// sharing. Only the PUBLIC anon key belongs here; never the service_role key.
const cfgUrl = process.env.SUPABASE_URL;
const cfgKey = process.env.SUPABASE_ANON_KEY;
const cfgDest = path.join(outDir, "config.js");
if (cfgUrl && cfgKey && !/YOUR_PROJECT_REF|YOUR_PUBLIC/.test(cfgUrl + cfgKey)) {
  fs.writeFileSync(
    cfgDest,
    `// Generated by scripts/build-netlify-site.js from build env vars.\nwindow.EU5_CONFIG = {\n  supabaseUrl: ${JSON.stringify(cfgUrl)},\n  supabaseAnonKey: ${JSON.stringify(cfgKey)},\n};\n`
  );
  console.log("Injected config.js (shared-save backend enabled).");
} else {
  fs.rmSync(cfgDest, { force: true }); // never ship a copied-in local config.js
  console.warn("SUPABASE_URL/SUPABASE_ANON_KEY not set - shared-save backend disabled in this build (sharing stays local-only).");
}

console.log(`Built static site in ${path.relative(root, outDir)}`);
